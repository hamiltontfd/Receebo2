/** Interpolated values are opaque: merchant names, products and amounts are not translated. */
export function appText(key: string, values: readonly (string | number)[] = [], locale: AppLocale = getAppLocale()): string {
  const entry = APP_COPY[key];
  const text = locale === "en" || !entry ? key : locale === "pt-BR" ? entry[1] ?? entry[0] : entry[0];
  const pluralized = values.length && typeof values[0] === "number"
    ? text.replace(/item\(ns\)/g, values[0] === 1 ? "item" : "itens")
        .replace(/\((s|m)\)/g, (_, suffix) => values[0] === 1 ? "" : suffix)
    : text;
  return pluralized.replace(/\{(\d+)\}/g, (token, index) => String(values[Number(index)] ?? token));
}

/** Categories retain their canonical API value even when their label changes. */
export function categoryText(category: string): string {
  if (getAppLocale() === "en") return category;
  return appText(category === "Home" ? "Household" : category);
}

/** Unknown server diagnostics must not leak English implementation text into the UI. */
export function appError(message: string | null | undefined, fallback: string): string {
  return appText(message && APP_COPY[message] ? message : fallback);
}
